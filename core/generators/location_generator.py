def _location_stub_ids(location_stubs: List[Dict[str, Any]]) -> List[str]:
    """Return a unique, ordered stub-ID list or reject the input contract."""
    ids = []
    for index, stub in enumerate(location_stubs):
        if not isinstance(stub, dict):
            raise ValueError(f"location stub {index} must be an object")
        location_id = stub.get("locationId")
        if not isinstance(location_id, str) or not location_id.strip():
            raise ValueError(f"location stub {index} has no useful locationId")
        ids.append(location_id)
    if len(ids) != len(set(ids)):
        raise ValueError("location stub IDs must be unique")
    return ids


def _canonicalize_t026_stub_owned_fields(
    parsed: Any,
    location_stubs: List[Dict[str, Any]],
) -> Any:
    """Restore only absent trusted fields from the ordered stub contract.

    Location IDs are generated by the map builder and are not model-authored
    content.  T026 also requires the returned array to preserve stub order, so
    an omitted ID can be restored positionally when count and object shape are
    intact.  A present-but-conflicting ID is evidence that order may be wrong;
    in that case this function changes nothing and the existing envelope gate
    keeps the full-batch retry/fail-closed behavior.

    The map builder also assigns each stub's initial dangerLevel from the area
    configuration.  Preserve model-authored variation when present, but restore
    an omitted value from a schema-valid stub so a weak model cannot discard
    already-established upstream state.
    """
    corrected = copy.deepcopy(parsed)
    expected_ids = _location_stub_ids(location_stubs)
    if not isinstance(corrected, dict):
        return corrected
    locations = corrected.get("locations")
    if not isinstance(locations, list) or len(locations) != len(expected_ids):
        return corrected
    if not all(isinstance(location, dict) for location in locations):
        return corrected

    # Preflight every present value before restoring any item.  This prevents
    # a partial repair from obscuring a reordered or duplicated model result.
    for index, location in enumerate(locations):
        returned_id = location.get("locationId")
        if returned_id is None or (
            isinstance(returned_id, str) and not returned_id.strip()
        ):
            continue
        if not isinstance(returned_id, str) or (
            returned_id.strip().casefold() != expected_ids[index].casefold()
        ):
            return copy.deepcopy(parsed)

    restored_id_indexes = []
    restored_danger_indexes = []
    for index, location in enumerate(locations):
        if location.get("locationId") != expected_ids[index]:
            location["locationId"] = expected_ids[index]
            restored_id_indexes.append(index)

        returned_danger = location.get("dangerLevel")
        stub_danger = location_stubs[index].get("dangerLevel")
        if (
            returned_danger is None
            or isinstance(returned_danger, str)
            and not returned_danger.strip()
        ) and stub_danger in _T026_DANGER_LEVELS:
            location["dangerLevel"] = stub_danger
            restored_danger_indexes.append(index)

    if restored_id_indexes:
        print(
            "WARNING: T026 restored "
            f"{len(restored_id_indexes)} omitted or format-only locationId "
            "value(s) from the trusted ordered stubs at indexes "
            f"{restored_id_indexes}."
        )
    if restored_danger_indexes:
        print(
            "WARNING: T026 restored "
            f"{len(restored_danger_indexes)} omitted or blank dangerLevel "
            "value(s) from the trusted ordered stubs at indexes "
            f"{restored_danger_indexes}."
        )
    return corrected


def _canonicalize_t026_response_fields(
    parsed: Any,
    location_stubs: List[Dict[str, Any]],
) -> Any:
    """Apply the bounded stub-owned and mechanical T026 canonicalizers."""
    with_stub_fields = _canonicalize_t026_stub_owned_fields(
        parsed,
        location_stubs,
    )
    return _canonicalize_t026_mechanical_fields(with_stub_fields)


def _canonicalize_t026_mechanical_fields(parsed: Any) -> Any:
    """Correct only unambiguous, machine-owned T026 syntax on a deep copy."""
    corrected = copy.deepcopy(parsed)
    if not isinstance(corrected, dict):
        return corrected
    locations = corrected.get("locations")
    if not isinstance(locations, list):
        return corrected

    for location in locations:
        if not isinstance(location, dict):
            continue
        location_id = location.get("locationId")

        # T026 creates a new module location before any play has occurred.
        # adventureSummary is living runtime history populated only after the
        # party leaves a location, so model-authored initial content is always
        # incorrect regardless of its type. Keep the required downstream field
        # while establishing its one valid initial state deterministically.
        location["adventureSummary"] = ""
        location["explorationState"] = {"status": "unvisited"}

        # Encounters are runtime-created records, not authored module content.
        # A fresh location has none: the shipped starter modules (e.g.
        # The_Thornwood_Watch, Keep_of_Doom) ship with empty encounters, and the
        # engine appends a dated encounter with the AUTHORITATIVE party-tracker
        # clock only when one actually occurs (core/managers/combat_manager.py
        # append; adv_summary/T015). Model-authored encounters carry invented
        # timestamps (Qwen produced day: 30 > the 28-day calendar, and years
        # 842/2024 vs the party's 1492) that are never the real clock but are fed
        # into DM narration context. Strip them deterministically so a weak model
        # can never inject a bad date or a phantom encounter into a new module.
        location["encounters"] = []

        checks = location.get("dcChecks")
        if isinstance(checks, list):
            for index, check in enumerate(checks):
                if not isinstance(check, str):
                    continue
                match = _T026_ABILITY_SKILL_CHECK.fullmatch(check)
                if match and match.group(1) in _T026_OFFICIAL_SKILLS:
                    checks[index] = f"{match.group(1)} {match.group(2)}"

        encounters = location.get("encounters")
        if not isinstance(encounters, list):
            continue
        for index, encounter in enumerate(encounters):
            if not isinstance(encounter, dict):
                continue
            if isinstance(location_id, str) and location_id:
                encounter["encounterId"] = f"{location_id}-E{index + 1}"
            world_conditions = encounter.get("worldConditions")
            if not isinstance(world_conditions, dict):
                continue
            month = world_conditions.get("month")
            if type(month) is int and 1 <= month <= len(_T026_CALENDAR_MONTHS):
                world_conditions["month"] = _T026_CALENDAR_MONTHS[month - 1]

    return corrected


@dataclass(frozen=True)
class _SchemaIssue:
    """One deterministic, user-prompt-safe schema issue."""

    path: str
    message: str


def _compact_issue_message(message: Any, limit: int = 240) -> str:
    """Bound model-derived validation text before it enters a retry prompt."""
    compact = " ".join(str(message).split())
    if len(compact) <= limit:
        return compact
    return compact[: limit - 3] + "..."


def _json_path(parts) -> str:
    """Render a jsonschema path deterministically as dotted/indexed JSON."""
    rendered = ""
    for part in parts:
        if isinstance(part, int):
            rendered += f"[{part}]"
        else:
            rendered += ("." if rendered else "") + str(part)
    return rendered or "$"


def _schema_issues(
    instance: Any,
    schema: Dict[str, Any],
    prefix=(),
) -> List[_SchemaIssue]:
    """Return all schema errors with stable paths and stable ordering."""
    validator = jsonschema.Draft7Validator(schema)
    errors = sorted(
        validator.iter_errors(instance),
        key=lambda error: (
            tuple(str(part) for part in error.absolute_path),
            str(error.validator),
            error.message,
        ),
    )
    issues = []
    for error in errors:
        path_parts = tuple(prefix) + tuple(error.absolute_path)
        if error.validator == "required" and isinstance(error.instance, dict):
            missing = sorted(
                key
                for key in error.validator_value
                if key not in error.instance
            )
            for key in missing:
                issues.append(
                    _SchemaIssue(
                        _json_path(path_parts + (key,)),
                        "required property is missing",
                    )
                )
            continue
        issues.append(
            _SchemaIssue(
                _json_path(path_parts),
                _compact_issue_message(error.message),
            )
        )
    return sorted(issues, key=lambda issue: (issue.path, issue.message))


def _format_schema_issues(issues: List[_SchemaIssue], limit: int = 24) -> str:
    """Compact schema feedback without embedding the full model response."""
    shown = issues[:limit]
    rendered = "; ".join(
        f"{issue.path}: {issue.message}" for issue in shown
    )
    if len(issues) > limit:
        rendered += f"; ... {len(issues) - limit} additional issue(s)"
    return rendered


def _validate_location_envelope(
    parsed: Any,
    location_stubs: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Validate the structure that makes positional replacement trustworthy."""
    expected_ids = _location_stub_ids(location_stubs)
    if not isinstance(parsed, dict):
        raise ValueError("$: location batch must be a JSON object")

    locations = parsed.get("locations")
    if not isinstance(locations, list):
        raise ValueError("locations: required array is missing or invalid")
    if len(locations) != len(expected_ids):
        raise ValueError(
            f"locations: expected exactly {len(expected_ids)} item(s), "
            f"got {len(locations)}"
        )
    for index, location in enumerate(locations):
        if not isinstance(location, dict):
            raise ValueError(f"locations[{index}]: location must be an object")
        returned_id = location.get("locationId")
        if returned_id != expected_ids[index]:
            returned_display = _compact_issue_message(repr(returned_id))
            raise ValueError(
                "locationId order mismatch at "
                f"locations[{index}].locationId: expected "
                f"{expected_ids[index]!r}, got {returned_display}"
            )
    return locations


def _location_item_schema(schema: Dict[str, Any]) -> Dict[str, Any]:
    """Extract a location schema, tolerating minimal unit-test schemas."""
    try:
        item_schema = schema["properties"]["locations"]["items"]
    except (KeyError, TypeError):
        return {}
    return item_schema if isinstance(item_schema, dict) else {}


def _invalid_location_issues(
    locations: List[Dict[str, Any]],
    schema: Dict[str, Any],
) -> Dict[int, List[_SchemaIssue]]:
    """Map invalid batch indexes to deterministic schema issues."""
    item_schema = _location_item_schema(schema)
    invalid = {}
    for index, location in enumerate(locations):
        issues = _schema_issues(
            location,
            item_schema,
            prefix=("locations", index),
        )
        if issues:
            invalid[index] = issues
    return invalid


def _schema_with_exact_location_count(
    schema: Dict[str, Any],
    expected_count: int,
) -> Dict[str, Any]:
    """Deep-copy a response schema and constrain only its locations count."""
    constrained = copy.deepcopy(schema)
    try:
        locations_schema = constrained["properties"]["locations"]
    except (KeyError, TypeError):
        return constrained
    if isinstance(locations_schema, dict):
        locations_schema["minItems"] = expected_count
        locations_schema["maxItems"] = expected_count
    return constrained


def _strict_openai_schema(schema: Any) -> Any:
    """Return the OpenAI strict-output subset without mutating the source."""
    if isinstance(schema, list):
        return [_strict_openai_schema(value) for value in schema]
    if not isinstance(schema, dict):
        return copy.deepcopy(schema)

    strict = {}
    for key, value in schema.items():
        if key in {"$schema", "examples"}:
            continue
        strict[key] = _strict_openai_schema(value)
    if strict.get("type") == "object" or "properties" in strict:
        strict["additionalProperties"] = False
        # OpenAI strict structured output requires every declared property at
        # every object level to appear in ``required``. Optionality in that
        # dialect is expressed by nullable types, not by omitting the key.
        # T026 canonicalizes runtime-owned optional fields after generation.
        strict["required"] = sorted(strict.get("properties", {}))
    return strict


def _t026_request_options(
    provider: str,
    main_cfg: Dict[str, Any],
    schema: Dict[str, Any],
    expected_count: int,
):
    """Build provider-native output controls for one T026 semantic call."""
    constrained = _schema_with_exact_location_count(schema, expected_count)
    extra_params = {
        key: value for key, value in main_cfg.items() if key != "model"
    }

    if provider in {"openai", "legacy"}:
        response_format = {
            "type": "json_schema",
            "json_schema": {
                "name": "t026_location_batch",
                "strict": True,
                "schema": _strict_openai_schema(constrained),
            },
        }
    elif provider == "gemini":
        # T026 requires complete objects, unlike partial-delta callsites that
        # deliberately use the converter's historical defaults.
        extra_params["response_schema"] = convert_to_gemini_schema(
            constrained,
            preserve_required=True,
            preserve_constraints=True,
        )
        response_format = {"type": "json_object"}
    elif provider == "lmstudio":
        # Local OpenAI-compatible servers disagree on schema-format support.
        # Explicitly use prompt-enforced JSON plus the same fail-closed local
        # validator. This is a capability policy, not an extra semantic retry.
        response_format = None
    else:
        raise ValueError(f"unsupported T026 provider: {provider}")

    return response_format, extra_params


class LocationBatchReasoningContentError(ValueError):
    """T026 received provider reasoning in the JSON content channel."""


_T026_REASONING_CONTENT_MESSAGE = (
    "$: model reasoning appeared in response content before the JSON. "
    "For LM Studio, enable separation of reasoning_content and content, "
    "or disable model thinking for this model/template."
)


def _parse_t026_response(raw: Any) -> Dict[str, Any]:
    """Parse one model response with a bounded, deterministic error message."""
    if not isinstance(raw, str):
        raise ValueError("$: response content must be a JSON string")

    # Some OpenAI-compatible local models occasionally wrap an otherwise valid
    # JSON response in one Markdown JSON fence despite the prompt contract.
    # Accept only a single complete outer fence with whitespace outside it.
    # This deliberately does not extract JSON from commentary, multiple code
    # blocks, or a partial fence, so the downstream fail-closed contract stays
    # intact.
    fenced = re.fullmatch(
        r"\s*```json[ \t]*\r?\n(?P<body>.*?)\r?\n```\s*",
        raw,
        flags=re.IGNORECASE | re.DOTALL,
    )
    content = fenced.group("body") if fenced else raw

    if re.match(r"<think(?:\s[^>]*)?>", content.lstrip(), flags=re.IGNORECASE):
        raise LocationBatchReasoningContentError(
            _T026_REASONING_CONTENT_MESSAGE
        )
    try:
        parsed = json.loads(content)
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"$: malformed JSON at line {exc.lineno}, column {exc.colno}"
        ) from exc
    if not isinstance(parsed, dict):
        raise ValueError("$: location batch must be a JSON object")
    return parsed


class LocationBatchCapacityError(RuntimeError):
    """T026 stopped because the selected model exhausted request capacity."""


_T026_CAPACITY_MESSAGE = (
    "Location generation stopped because the selected model reached its "
    "output or context capacity. No invalid location batch was saved. "
    "Increase the model's context/output limit, reduce the module size, or "
    "choose another model."
)

_T026_INVALID_RESPONSE_MESSAGE = (
    "Location batch generation returned invalid JSON or contract data after "
    "2 attempts. The selected model could not produce the required location "
    "data. No invalid location batch was saved. Retry, reconfigure the local "
    "model, or select another model."
)


def _is_capacity_finish_reason(reason: Any) -> bool:
    """Recognize explicit capacity stops without guessing from content."""
    return isinstance(reason, str) and reason.strip().lower() in {
        "length",
        "max_tokens",
    }


def _is_structured_context_limit_error(
    error: api_client.ProviderCallError,
) -> bool:
    """Recognize explicit context-limit codes from a provider exception."""
    original = getattr(error, "original_error", None)
    codes = [getattr(original, "code", None)]
    body = getattr(original, "body", None)
    if isinstance(body, dict):
        codes.append(body.get("code"))
        nested = body.get("error")
        if isinstance(nested, dict):
            codes.append(nested.get("code"))
    known_codes = {
        "context_length_exceeded",
        "context_window_exceeded",
        "max_context_length",
    }
    return any(
        isinstance(code, str) and code.strip().lower() in known_codes
        for code in codes
    )


def _validate_location_batch_contract(
    parsed: Any,
    location_stubs: List[Dict[str, Any]],
    schema: Dict[str, Any],
) -> Dict[str, Any]:
    """Final T026 schema/count/ID/order gate; return an ownership-safe copy."""
    _validate_location_envelope(parsed, location_stubs)
    issues = _schema_issues(parsed, schema)
    if issues:
        raise ValueError(
            f"schema validation failed: {_format_schema_issues(issues)}"
        )
    return copy.deepcopy(parsed)


